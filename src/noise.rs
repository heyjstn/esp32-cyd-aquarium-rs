fn fast_floor(f: f32) -> i32 {
    if f >= 0.0 {
        f as i32
    } else {
        f as i32 - 1
    }
}

fn hash(seed: i32, x_primed: i32, y_primed: i32) -> i32 {
    let mut h = seed ^ x_primed ^ y_primed;
    h = h.wrapping_mul(0x27d4eb2d);
    h
}

fn grad_coord(seed: i32, x_primed: i32, y_primed: i32, xd: f32, yd: f32) -> f32 {
    let mut h = hash(seed, x_primed, y_primed);
    h ^= h >> 15;
    h &= 127 << 1;

    let xg = GRADIENTS_2D[h as usize];
    let yg = GRADIENTS_2D[(h | 1) as usize];

    xd * xg + yd * yg
}

/// FastNoiseLite configured like the creature motions do:
/// NoiseType_OpenSimplex2S + SetFrequency, default seed 1337.
pub struct OpenSimplex2S {
    seed: i32,
    frequency: f32,
}

impl OpenSimplex2S {
    pub fn new(frequency: f32) -> Self {
        Self { seed: 1337, frequency }
    }

    /// FastNoiseLite GetNoise(x, y), including TransformNoiseCoordinate's
    /// frequency scaling and OpenSimplex2 skew.
    pub fn get_noise(&self, x: f32, y: f32) -> f32 {
        const SQRT3: f32 = 1.7320508075688772;
        const F2: f32 = 0.5 * (SQRT3 - 1.0);

        let mut x = x * self.frequency;
        let mut y = y * self.frequency;
        let t = (x + y) * F2;
        x += t;
        y += t;

        self.single(x, y)
    }

    fn single(&self, x: f32, y: f32) -> f32 {
        const SQRT3: f32 = 1.7320508075688772;
        const G2: f32 = (3.0 - SQRT3) / 6.0;

        let i = fast_floor(x);
        let j = fast_floor(y);
        let xi = x - i as f32;
        let yi = y - j as f32;

        let i = i.wrapping_mul(PRIME_X);
        let j = j.wrapping_mul(PRIME_Y);
        let i1 = i.wrapping_add(PRIME_X);
        let j1 = j.wrapping_add(PRIME_Y);

        let t = (xi + yi) * G2;
        let x0 = xi - t;
        let y0 = yi - t;

        let a0 = (2.0 / 3.0) - x0 * x0 - y0 * y0;
        let mut value = (a0 * a0) * (a0 * a0) * grad_coord(self.seed, i, j, x0, y0);

        let a1 = (2.0 * (1.0 - 2.0 * G2) * (1.0 / G2 - 2.0)) * t + (-2.0 * (1.0 - 2.0 * G2) * (1.0 - 2.0 * G2) + a0);
        let x1 = x0 - (1.0 - 2.0 * G2);
        let y1 = y0 - (1.0 - 2.0 * G2);
        value += (a1 * a1) * (a1 * a1) * grad_coord(self.seed, i1, j1, x1, y1);

        let xmyi = xi - yi;
        if t > G2 {
            if xi + xmyi > 1.0 {
                let x2 = x0 + (3.0 * G2 - 2.0);
                let y2 = y0 + (3.0 * G2 - 1.0);
                let a2 = (2.0 / 3.0) - x2 * x2 - y2 * y2;
                if a2 > 0.0 {
                    value += (a2 * a2) * (a2 * a2)
                        * grad_coord(self.seed, i.wrapping_add(PRIME_X << 1), j.wrapping_add(PRIME_Y), x2, y2);
                }
            } else {
                let x2 = x0 + G2;
                let y2 = y0 + (G2 - 1.0);
                let a2 = (2.0 / 3.0) - x2 * x2 - y2 * y2;
                if a2 > 0.0 {
                    value += (a2 * a2) * (a2 * a2) * grad_coord(self.seed, i, j.wrapping_add(PRIME_Y), x2, y2);
                }
            }

            if yi - xmyi > 1.0 {
                let x3 = x0 + (3.0 * G2 - 1.0);
                let y3 = y0 + (3.0 * G2 - 2.0);
                let a3 = (2.0 / 3.0) - x3 * x3 - y3 * y3;
                if a3 > 0.0 {
                    value += (a3 * a3) * (a3 * a3)
                        * grad_coord(self.seed, i.wrapping_add(PRIME_X), j.wrapping_add(PRIME_Y << 1), x3, y3);
                }
            } else {
                let x3 = x0 + (G2 - 1.0);
                let y3 = y0 + G2;
                let a3 = (2.0 / 3.0) - x3 * x3 - y3 * y3;
                if a3 > 0.0 {
                    value += (a3 * a3) * (a3 * a3) * grad_coord(self.seed, i.wrapping_add(PRIME_X), j, x3, y3);
                }
            }
        } else {
            if xi + xmyi < 0.0 {
                let x2 = x0 + (1.0 - G2);
                let y2 = y0 - G2;
                let a2 = (2.0 / 3.0) - x2 * x2 - y2 * y2;
                if a2 > 0.0 {
                    value += (a2 * a2) * (a2 * a2)
                        * grad_coord(self.seed, i.wrapping_sub(PRIME_X), j, x2, y2);
                }
            } else {
                let x2 = x0 + (G2 - 1.0);
                let y2 = y0 + G2;
                let a2 = (2.0 / 3.0) - x2 * x2 - y2 * y2;
                if a2 > 0.0 {
                    value += (a2 * a2) * (a2 * a2) * grad_coord(self.seed, i.wrapping_add(PRIME_X), j, x2, y2);
                }
            }

            if yi < xmyi {
                let x2 = x0 - G2;
                let y2 = y0 - (G2 - 1.0);
                let a2 = (2.0 / 3.0) - x2 * x2 - y2 * y2;
                if a2 > 0.0 {
                    value += (a2 * a2) * (a2 * a2)
                        * grad_coord(self.seed, i, j.wrapping_sub(PRIME_Y), x2, y2);
                }
            } else {
                let x2 = x0 + G2;
                let y2 = y0 - (G2 - 1.0);
                let a2 = (2.0 / 3.0) - x2 * x2 - y2 * y2;
                if a2 > 0.0 {
                    value += (a2 * a2) * (a2 * a2) * grad_coord(self.seed, i, j.wrapping_add(PRIME_Y), x2, y2);
                }
            }
        }

        value * 18.24196194486065
    }
}

#[cfg(test)]
