    #[test]
    fn simplex_stays_bounded() {
        let n = OpenSimplex2S::new(0.01);
        for i in 0..2000 {
            let v = n.get_noise(i as f32 * 13.7, i as f32 * 7.3);
            assert!((-1.1..=1.1).contains(&v), "out of range: {v}");
        }
    }

    #[test]
    fn simplex_varies() {
        let n = OpenSimplex2S::new(0.01);
        let a = n.get_noise(0.0, 0.0);
        let b = n.get_noise(500.0, 500.0);
        assert!((a - b).abs() > 1e-6);
    }

    #[test]
    fn simplex_frequency_scales() {
        let slow = OpenSimplex2S::new(0.001);
        let fast = OpenSimplex2S::new(0.1);
        assert_ne!(slow.get_noise(50.0, 50.0), fast.get_noise(50.0, 50.0));
    }
