    use super::*;

    #[test]
    fn inoise8_is_deterministic() {
        assert_eq!(inoise8(0, 0, 0), inoise8(0, 0, 0));
        assert_eq!(inoise8(320, 1050, 77), inoise8(320, 1050, 77));
    }

    #[test]
    fn inoise8_regression_vectors() {
        // Snapshot of the ported implementation; guards against accidental
        // changes when refactoring.
        let vectors = [
            (0, 0, 0),
            (256, 256, 256),
            (100, 200, 300),
            (1600, 2120, 1234),
            (65535, 65535, 65535),
        ];
        let expected = [128u8, 128, 106, 166, 126];
        for ((x, y, z), want) in vectors.into_iter().zip(expected) {
            assert_eq!(inoise8(x, y, z), want, "inoise8({x},{y},{z})");
        }
    }

    #[test]
    fn inoise8_varies_over_space() {
        let mut distinct = std::collections::BTreeSet::new();
        for i in 0..64u16 {
            distinct.insert(inoise8(i * 40, i * 20, i * 10));
        }
        assert!(distinct.len() > 8, "noise should vary, got {distinct:?}");
    }

