fn p(x: u8) -> u8 {
    P[x as usize]
}

fn grad8_3d(hash: u8, x: i8, y: i8, z: i8) -> i8 {
    let hash = hash & 0xF;
    let mut u = if hash & 8 != 0 { y } else { x };
    let mut v = if hash < 4 {
        y
    } else if hash == 12 || hash == 14 {
        x
    } else {
        z
    };
    if hash & 1 != 0 {
        u = u.wrapping_neg();
    }
    if hash & 2 != 0 {
        v = v.wrapping_neg();
    }
    avg7(u, v)
}

fn inoise8_raw_3d(x: u16, y: u16, z: u16) -> i8 {
    // Find the unit cube containing the point.
    let cube_x = (x >> 8) as u8;
    let cube_y = (y >> 8) as u8;
    let cube_z = (z >> 8) as u8;

    // Hash cube corner coordinates (wrapping, like FastLED's uint8_t math).
    let a = p(cube_x).wrapping_add(cube_y);
    let aa = p(a).wrapping_add(cube_z);
    let ab = p(a.wrapping_add(1)).wrapping_add(cube_z);
    let b = p(cube_x.wrapping_add(1)).wrapping_add(cube_y);
    let ba = p(b).wrapping_add(cube_z);
    let bb = p(b.wrapping_add(1)).wrapping_add(cube_z);

    // Relative position of the point in the cube.
    let mut u = x as u8;
    let mut v = y as u8;
    let mut w = z as u8;

    // Signed version of the above for the grad function.
    let xx = ((x as u8) >> 1) as i8 & 0x7F;
    let yy = ((y as u8) >> 1) as i8 & 0x7F;
    let zz = ((z as u8) >> 1) as i8 & 0x7F;
    let n: i8 = -128; // 0x80

    u = ease8_in_out_quad(u);
    v = ease8_in_out_quad(v);
    w = ease8_in_out_quad(w);

    let x1 = lerp7by8(grad8_3d(p(aa), xx, yy, zz), grad8_3d(p(ba), xx.wrapping_sub(n), yy, zz), u);
    let x2 = lerp7by8(
        grad8_3d(p(ab), xx, yy.wrapping_sub(n), zz),
        grad8_3d(p(bb), xx.wrapping_sub(n), yy.wrapping_sub(n), zz),
        u,
    );
    let x3 = lerp7by8(
        grad8_3d(p(aa.wrapping_add(1)), xx, yy, zz.wrapping_sub(n)),
        grad8_3d(p(ba.wrapping_add(1)), xx.wrapping_sub(n), yy, zz.wrapping_sub(n)),
        u,
    );
    let x4 = lerp7by8(
        grad8_3d(p(ab.wrapping_add(1)), xx, yy.wrapping_sub(n), zz.wrapping_sub(n)),
        grad8_3d(
            p(bb.wrapping_add(1)),
            xx.wrapping_sub(n),
            yy.wrapping_sub(n),
            zz.wrapping_sub(n),
        ),
        u,
    );

    let y1 = lerp7by8(x1, x2, v);
    let y2 = lerp7by8(x3, x4, v);

    lerp7by8(y1, y2, w)
}

/// FastLED inoise8(x, y, z): 3D noise returning 0..=255.
pub fn inoise8(x: u16, y: u16, z: u16) -> u8 {
    let n = inoise8_raw_3d(x, y, z); // -64..+64
    let n = n.wrapping_add(64); //      0..128
    qadd8(n as u8, n as u8) //          0..255
}

